"""Direct MLX baseline runner for controlled experimental comparisons.

Executes identical workload scenarios directly against MLX and MLX-LM without
passing through the InferOpt scheduler, establishing an unmediated baseline.
"""

import asyncio
import hashlib
import math
import platform
import time
import uuid
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from inferopt.backends.mlx import DEFAULT_MODEL_ID
from inferopt.benchmarks.models import ArrivalPattern, WorkloadRequestSpec, WorkloadScenario
from inferopt.core.exceptions import BackendError
from inferopt.telemetry.collector import _compute_percentile


def compute_sha256(text: str) -> str:
    """Calculate SHA-256 hexadecimal hash of input text."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def calculate_percentile(values: list[float], p: float) -> float:
    """Calculate p-th percentile of an unsorted list of values."""
    return _compute_percentile(sorted(values), p)


def compute_std_dev(values: list[float], mean_val: float | None = None) -> float:
    """Compute sample standard deviation of a list of floats."""
    n = len(values)
    if n <= 1:
        return 0.0
    mean = mean_val if mean_val is not None else (sum(values) / n)
    variance = sum((x - mean) ** 2 for x in values) / (n - 1)
    return math.sqrt(variance)


class DirectMLXRequestResult(BaseModel):
    """Result and metrics for a single request executed directly against MLX."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    request_id: str = Field(description="Unique request identifier")
    prompt: str = Field(description="Original input prompt")
    prompt_hash: str = Field(default="", description="SHA-256 hash of input prompt")
    generated_text: str = Field(default="", description="Text generated by MLX")
    output_hash: str = Field(default="", description="SHA-256 hash of generated output")
    input_tokens: int = Field(default=0, ge=0, description="Exact prompt token count")
    output_tokens: int = Field(default=0, ge=0, description="Exact generated token count")
    latency_ms: float = Field(default=0.0, ge=0.0, description="Turnaround execution latency in ms")
    success: bool = Field(default=True, description="True if generation succeeded")
    error_message: str | None = Field(default=None, description="Error message if failed")


class DirectMLXResult(BaseModel):
    """Aggregated baseline result for a workload scenario executed directly via MLX."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    baseline_id: str = Field(description="Unique baseline execution ID")
    timestamp: float = Field(description="Execution start timestamp")
    scenario_name: str = Field(description="Name of evaluated workload scenario")
    model_id: str = Field(description="Hugging Face model identifier")
    duration_sec: float = Field(ge=0.0, description="Total benchmark run duration in seconds")
    total_requests: int = Field(ge=0, description="Total number of submitted requests")
    completed_requests: int = Field(ge=0, description="Number of successfully completed requests")
    failed_requests: int = Field(default=0, ge=0, description="Number of failed requests")
    requests_per_sec: float = Field(ge=0.0, description="Completed requests per second")
    output_tokens_per_sec: float = Field(ge=0.0, description="Generated output tokens per second")
    total_input_tokens: int = Field(ge=0, description="Sum of prompt tokens across requests")
    total_output_tokens: int = Field(ge=0, description="Sum of generated tokens across requests")
    avg_input_tokens_per_req: float = Field(
        default=0.0, ge=0.0, description="Average prompt tokens per request"
    )
    avg_output_tokens_per_req: float = Field(
        default=0.0, ge=0.0, description="Average generated tokens per request"
    )
    min_output_tokens: int = Field(
        default=0, ge=0, description="Minimum generated tokens in a single request"
    )
    max_output_tokens: int = Field(
        default=0, ge=0, description="Maximum generated tokens in a single request"
    )
    avg_latency_ms: float = Field(ge=0.0, description="Mean request latency in ms")
    p50_latency_ms: float = Field(ge=0.0, description="Median request latency in ms")
    p95_latency_ms: float = Field(ge=0.0, description="95th percentile request latency in ms")
    p99_latency_ms: float = Field(ge=0.0, description="99th percentile request latency in ms")
    min_latency_ms: float = Field(default=0.0, ge=0.0, description="Minimum request latency in ms")
    max_latency_ms: float = Field(default=0.0, ge=0.0, description="Maximum request latency in ms")
    std_dev_latency_ms: float = Field(
        default=0.0, ge=0.0, description="Standard deviation of request latencies in ms"
    )
    request_results: tuple[DirectMLXRequestResult, ...] = Field(
        default_factory=tuple, description="Ordered per-request results"
    )
    warmup_count: int = Field(default=0, ge=0, description="Number of warmup requests executed")
    model_load_time_ms: float = Field(
        default=0.0, ge=0.0, description="Cold start model load time in ms"
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict, description="Execution environment and runtime metadata"
    )


class DirectMLXRunner:
    """Direct MLX execution engine bypassing InferOpt control plane."""

    def __init__(
        self,
        model_id: str = DEFAULT_MODEL_ID,
        default_temperature: float = 0.0,
        default_max_tokens: int = 128,
    ) -> None:
        """Initialize Direct MLX runner.

        Args:
            model_id: Hugging Face model identifier.
            default_temperature: Sampling temperature (0.0 for greedy argmax).
            default_max_tokens: Default maximum tokens per request.
        """
        self._model_id = model_id
        self._default_temperature = default_temperature
        self._default_max_tokens = default_max_tokens
        self._model: Any = None
        self._tokenizer: Any = None
        self._model_load_time_ms: float = 0.0
        self._lock = asyncio.Lock()

    @property
    def model_id(self) -> str:
        """Target model identifier."""
        return self._model_id

    @property
    def is_loaded(self) -> bool:
        """True if model and tokenizer are loaded in memory."""
        return self._model is not None and self._tokenizer is not None

    @property
    def model_load_time_ms(self) -> float:
        """Measured cold start model load time in milliseconds."""
        return self._model_load_time_ms

    async def load_model(self) -> None:
        """Load model and tokenizer into memory if not already loaded."""
        if self.is_loaded:
            return

        async with self._lock:
            if self.is_loaded:
                return

            def _load_sync() -> tuple[Any, Any, float]:
                try:
                    import mlx_lm
                except ImportError as err:
                    raise BackendError(
                        "MLX dependencies not installed. Install with: pip install 'inferopt[mlx]'"
                    ) from err

                t0 = time.perf_counter()
                try:
                    res = mlx_lm.load(self._model_id)
                    load_ms = (time.perf_counter() - t0) * 1000.0
                    return res[0], res[1], load_ms
                except Exception as exc:
                    raise BackendError(
                        f"Failed loading MLX model '{self._model_id}': {exc}"
                    ) from exc

            self._model, self._tokenizer, self._model_load_time_ms = await asyncio.to_thread(
                _load_sync
            )

    async def warmup(self, count: int = 1) -> None:
        """Execute warmup requests to initialize Metal pipelines, discarding results.

        Args:
            count: Number of warmup iterations to execute.
        """
        if count <= 0:
            return

        await self.load_model()

        def _warmup_sync() -> None:
            import contextlib

            try:
                import mlx_lm
                import mlx_lm.sample_utils
            except ImportError:
                return

            sampler = mlx_lm.sample_utils.make_sampler(temp=0.0)
            for _ in range(count):
                with contextlib.suppress(Exception):
                    mlx_lm.generate(
                        self._model,
                        self._tokenizer,
                        prompt="Warmup inference step.",
                        max_tokens=8,
                        sampler=sampler,
                        verbose=False,
                    )

        await asyncio.to_thread(_warmup_sync)

    async def run(
        self,
        scenario: WorkloadScenario,
        warmup_count: int = 0,
        metadata: dict[str, Any] | None = None,
    ) -> DirectMLXResult:
        """Execute workload scenario directly against MLX (Condition A).

        Args:
            scenario: WorkloadScenario containing requests and arrival specifications.
            warmup_count: Number of unmeasured warmup requests to execute before timing.
            metadata: Optional additional execution metadata.

        Returns:
            DirectMLXResult containing all per-request metrics and statistical summaries.
        """
        await self.load_model()

        if warmup_count > 0:
            await self.warmup(count=warmup_count)

        start_time = time.perf_counter()
        request_results = await self._dispatch_workload(scenario)
        duration_sec = max(0.0001, time.perf_counter() - start_time)

        return self._build_result(
            scenario=scenario,
            request_results=request_results,
            duration_sec=duration_sec,
            warmup_count=warmup_count,
            metadata=metadata,
        )

    async def run_native_batch(
        self,
        scenario: WorkloadScenario,
        warmup_count: int = 0,
        metadata: dict[str, Any] | None = None,
    ) -> DirectMLXResult:
        """Execute workload scenario via native MLX batch_generate (Condition B).

        Args:
            scenario: WorkloadScenario containing requests to execute in native batch.
            warmup_count: Number of unmeasured warmup requests to execute before timing.
            metadata: Optional additional execution metadata.

        Returns:
            DirectMLXResult containing all per-request metrics and statistical summaries.
        """
        await self.load_model()

        if warmup_count > 0:
            await self.warmup(count=warmup_count)

        start_time = time.perf_counter()
        request_results = await self._generate_native_batch(scenario)
        duration_sec = max(0.0001, time.perf_counter() - start_time)

        return self._build_result(
            scenario=scenario,
            request_results=request_results,
            duration_sec=duration_sec,
            warmup_count=warmup_count,
            metadata=metadata,
        )

    def _build_result(
        self,
        scenario: WorkloadScenario,
        request_results: list[DirectMLXRequestResult],
        duration_sec: float,
        warmup_count: int,
        metadata: dict[str, Any] | None = None,
    ) -> DirectMLXResult:
        """Build a DirectMLXResult from raw request results and run duration."""
        completed = [r for r in request_results if r.success]
        failed = [r for r in request_results if not r.success]

        total_input_tokens = sum(r.input_tokens for r in completed)
        total_output_tokens = sum(r.output_tokens for r in completed)

        req_per_sec = len(completed) / duration_sec if duration_sec > 0 else 0.0
        out_tok_per_sec = total_output_tokens / duration_sec if duration_sec > 0 else 0.0

        avg_in_tok = total_input_tokens / len(completed) if completed else 0.0
        avg_out_tok = total_output_tokens / len(completed) if completed else 0.0
        min_out_tok = min((r.output_tokens for r in completed), default=0)
        max_out_tok = max((r.output_tokens for r in completed), default=0)

        latencies = [r.latency_ms for r in completed]
        avg_lat = sum(latencies) / len(latencies) if latencies else 0.0
        p50_lat = calculate_percentile(latencies, 50.0) if latencies else 0.0
        p95_lat = calculate_percentile(latencies, 95.0) if latencies else 0.0
        p99_lat = calculate_percentile(latencies, 99.0) if latencies else 0.0
        min_lat = min(latencies) if latencies else 0.0
        max_lat = max(latencies) if latencies else 0.0
        std_dev_lat = compute_std_dev(latencies, avg_lat) if latencies else 0.0

        run_metadata = {
            "platform": platform.platform(),
            "machine": platform.machine(),
            "python_version": platform.python_version(),
            **(metadata or {}),
        }

        return DirectMLXResult(
            baseline_id=f"direct-mlx-{uuid.uuid4().hex[:8]}",
            timestamp=time.time(),
            scenario_name=scenario.scenario_name,
            model_id=self._model_id,
            duration_sec=duration_sec,
            total_requests=len(request_results),
            completed_requests=len(completed),
            failed_requests=len(failed),
            requests_per_sec=req_per_sec,
            output_tokens_per_sec=out_tok_per_sec,
            total_input_tokens=total_input_tokens,
            total_output_tokens=total_output_tokens,
            avg_input_tokens_per_req=avg_in_tok,
            avg_output_tokens_per_req=avg_out_tok,
            min_output_tokens=min_out_tok,
            max_output_tokens=max_out_tok,
            avg_latency_ms=avg_lat,
            p50_latency_ms=p50_lat,
            p95_latency_ms=p95_lat,
            p99_latency_ms=p99_lat,
            min_latency_ms=min_lat,
            max_latency_ms=max_lat,
            std_dev_latency_ms=std_dev_lat,
            request_results=tuple(request_results),
            warmup_count=warmup_count,
            model_load_time_ms=self._model_load_time_ms,
            metadata=run_metadata,
        )

    async def _dispatch_workload(self, scenario: WorkloadScenario) -> list[DirectMLXRequestResult]:
        """Dispatch workload requests according to arrival pattern."""
        pattern = scenario.config.arrival_pattern

        if pattern == ArrivalPattern.SEQUENTIAL:
            results: list[DirectMLXRequestResult] = []
            for spec in scenario.requests:
                results.append(await self._generate_single(spec))
            return results
        elif pattern in (ArrivalPattern.CONCURRENT, ArrivalPattern.BURST):
            tasks = [self._generate_single(spec) for spec in scenario.requests]
            return list(await asyncio.gather(*tasks))
        elif pattern == ArrivalPattern.FIXED_RATE:
            rate_rps = scenario.config.arrival_rate_rps or 10.0
            start_time = time.perf_counter()

            async def _scheduled(
                spec: WorkloadRequestSpec, offset: float
            ) -> DirectMLXRequestResult:
                remaining = offset - (time.perf_counter() - start_time)
                if remaining > 0:
                    await asyncio.sleep(remaining)
                return await self._generate_single(spec)

            tasks = [_scheduled(spec, idx / rate_rps) for idx, spec in enumerate(scenario.requests)]
            return list(await asyncio.gather(*tasks))
        else:
            tasks = [self._generate_single(spec) for spec in scenario.requests]
            return list(await asyncio.gather(*tasks))

    async def _generate_single(self, spec: WorkloadRequestSpec) -> DirectMLXRequestResult:
        """Execute a single request directly via MLX in worker thread."""
        max_tokens = spec.max_tokens if spec.max_tokens > 0 else self._default_max_tokens
        temperature = spec.temperature if spec.temperature >= 0.0 else self._default_temperature
        p_hash = compute_sha256(spec.prompt)

        def _sync_gen() -> tuple[str, str, int, int, float]:
            import mlx_lm
            import mlx_lm.sample_utils

            t0 = time.perf_counter()

            try:
                prompt_tokens = (
                    len(self._tokenizer.encode(spec.prompt))
                    if hasattr(self._tokenizer, "encode")
                    else 0
                )
            except Exception:
                prompt_tokens = 0

            sampler = mlx_lm.sample_utils.make_sampler(temp=temperature)
            generated_text = mlx_lm.generate(
                self._model,
                self._tokenizer,
                prompt=spec.prompt,
                max_tokens=max_tokens,
                sampler=sampler,
                verbose=False,
            )
            lat_ms = max(0.0, (time.perf_counter() - t0) * 1000.0)
            out_hash = compute_sha256(generated_text)

            try:
                output_tokens = (
                    len(self._tokenizer.encode(generated_text))
                    if hasattr(self._tokenizer, "encode")
                    else 0
                )
            except Exception:
                output_tokens = 0

            return generated_text, out_hash, prompt_tokens, output_tokens, lat_ms

        try:
            text, out_hash, in_tok, out_tok, lat_ms = await asyncio.to_thread(_sync_gen)
            return DirectMLXRequestResult(
                request_id=spec.request_id,
                prompt=spec.prompt,
                prompt_hash=p_hash,
                generated_text=text,
                output_hash=out_hash,
                input_tokens=in_tok,
                output_tokens=out_tok,
                latency_ms=lat_ms,
                success=True,
            )
        except Exception as exc:
            return DirectMLXRequestResult(
                request_id=spec.request_id,
                prompt=spec.prompt,
                prompt_hash=p_hash,
                generated_text="",
                output_hash="",
                input_tokens=0,
                output_tokens=0,
                latency_ms=0.0,
                success=False,
                error_message=str(exc),
            )

    async def _generate_native_batch(
        self, scenario: WorkloadScenario
    ) -> list[DirectMLXRequestResult]:
        """Execute all scenario requests directly via native MLX batch_generate."""

        def _sync_batch_gen() -> list[DirectMLXRequestResult]:
            try:
                import mlx_lm
            except ImportError as err:
                raise BackendError(
                    "MLX dependencies not installed. Install with: pip install 'inferopt[mlx]'"
                ) from err

            t0 = time.perf_counter()
            encoded_prompts: list[list[int]] = []
            max_tokens_list: list[int] = []
            prompt_hashes: list[str] = []

            for spec in scenario.requests:
                p_hash = compute_sha256(spec.prompt)
                prompt_hashes.append(p_hash)
                try:
                    toks = self._tokenizer.encode(spec.prompt)
                    encoded_prompts.append(toks)
                except Exception:
                    encoded_prompts.append([])

                m_tok = spec.max_tokens if spec.max_tokens > 0 else self._default_max_tokens
                max_tokens_list.append(m_tok)

            try:
                batch_response = mlx_lm.batch_generate(
                    self._model,
                    self._tokenizer,
                    prompts=encoded_prompts,
                    max_tokens=max_tokens_list,
                    verbose=False,
                )
            except Exception as exc:
                return [
                    DirectMLXRequestResult(
                        request_id=spec.request_id,
                        prompt=spec.prompt,
                        prompt_hash=p_hash,
                        generated_text="",
                        output_hash="",
                        input_tokens=0,
                        output_tokens=0,
                        latency_ms=0.0,
                        success=False,
                        error_message=str(exc),
                    )
                    for spec, p_hash in zip(scenario.requests, prompt_hashes, strict=False)
                ]

            batch_latency_ms = max(0.0, (time.perf_counter() - t0) * 1000.0)
            res_list: list[DirectMLXRequestResult] = []

            for idx, (spec, text, p_hash) in enumerate(
                zip(scenario.requests, batch_response.texts, prompt_hashes, strict=False)
            ):
                out_hash = compute_sha256(text)
                in_tok = len(encoded_prompts[idx])
                try:
                    out_tok = len(self._tokenizer.encode(text))
                except Exception:
                    out_tok = 0

                res_list.append(
                    DirectMLXRequestResult(
                        request_id=spec.request_id,
                        prompt=spec.prompt,
                        prompt_hash=p_hash,
                        generated_text=text,
                        output_hash=out_hash,
                        input_tokens=in_tok,
                        output_tokens=out_tok,
                        latency_ms=batch_latency_ms,
                        success=True,
                    )
                )

            return res_list

        try:
            return await asyncio.to_thread(_sync_batch_gen)
        except Exception as exc:
            return [
                DirectMLXRequestResult(
                    request_id=spec.request_id,
                    prompt=spec.prompt,
                    prompt_hash=compute_sha256(spec.prompt),
                    generated_text="",
                    output_hash="",
                    input_tokens=0,
                    output_tokens=0,
                    latency_ms=0.0,
                    success=False,
                    error_message=str(exc),
                )
                for spec in scenario.requests
            ]
