"""Direct vLLM baseline runner for controlled experimental comparisons.

Executes identical workload scenarios directly against the vLLM engine without
passing through the InferOpt scheduler, establishing an unmediated baseline.
"""

import asyncio
import hashlib
import math
import time
import uuid
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from inferopt.backends.vllm import DEFAULT_VLLM_MODEL_ID, VLLMConfig
from inferopt.benchmarks.models import WorkloadRequestSpec, WorkloadScenario
from inferopt.core.exceptions import BackendError
from inferopt.telemetry.collector import _compute_percentile


def compute_sha256(text: str) -> str:
    """Calculate SHA-256 hexadecimal hash of input text."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def calculate_percentile(values: list[float], p: float) -> float:
    """Calculate p-th percentile of an unsorted list of values."""
    return _compute_percentile(sorted(values), p)


def compute_std_dev(values: list[float], mean_val: float | None = None) -> float:
    """Compute sample standard deviation of a list of floats."""
    n = len(values)
    if n <= 1:
        return 0.0
    mean = mean_val if mean_val is not None else (sum(values) / n)
    variance = sum((x - mean) ** 2 for x in values) / (n - 1)
    return math.sqrt(variance)


class DirectVLLMRequestResult(BaseModel):
    """Result and metrics for a single request executed directly against vLLM."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    request_id: str = Field(description="Unique request identifier")
    prompt: str = Field(description="Original input prompt")
    prompt_hash: str = Field(default="", description="SHA-256 hash of input prompt")
    generated_text: str = Field(default="", description="Text generated by vLLM")
    output_hash: str = Field(default="", description="SHA-256 hash of generated output")
    input_tokens: int = Field(default=0, ge=0, description="Exact prompt token count")
    output_tokens: int = Field(default=0, ge=0, description="Exact generated token count")
    latency_ms: float = Field(default=0.0, ge=0.0, description="Turnaround execution latency in ms")
    success: bool = Field(default=True, description="True if generation succeeded")
    error_message: str | None = Field(default=None, description="Error message if failed")


class DirectVLLMResult(BaseModel):
    """Aggregated baseline result for a workload scenario executed directly via vLLM."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    baseline_id: str = Field(description="Unique baseline execution ID")
    timestamp: float = Field(description="Execution start timestamp")
    scenario_name: str = Field(description="Name of evaluated workload scenario")
    model_id: str = Field(description="Hugging Face model identifier")
    duration_sec: float = Field(ge=0.0, description="Total benchmark run duration in seconds")
    total_requests: int = Field(ge=0, description="Total number of submitted requests")
    completed_requests: int = Field(ge=0, description="Number of successfully completed requests")
    failed_requests: int = Field(default=0, ge=0, description="Number of failed requests")
    requests_per_sec: float = Field(ge=0.0, description="Completed requests per second")
    output_tokens_per_sec: float = Field(ge=0.0, description="Generated output tokens per second")
    total_input_tokens: int = Field(ge=0, description="Sum of prompt tokens across requests")
    total_output_tokens: int = Field(ge=0, description="Sum of generated tokens across requests")
    avg_input_tokens_per_req: float = Field(
        default=0.0, ge=0.0, description="Average prompt tokens per request"
    )
    avg_output_tokens_per_req: float = Field(
        default=0.0, ge=0.0, description="Average generated tokens per request"
    )
    min_output_tokens: int = Field(
        default=0, ge=0, description="Minimum generated tokens in a single request"
    )
    max_output_tokens: int = Field(
        default=0, ge=0, description="Maximum generated tokens in a single request"
    )
    avg_latency_ms: float = Field(ge=0.0, description="Mean request latency in ms")
    p50_latency_ms: float = Field(ge=0.0, description="Median request latency in ms")
    p95_latency_ms: float = Field(ge=0.0, description="95th percentile request latency in ms")
    p99_latency_ms: float = Field(ge=0.0, description="99th percentile request latency in ms")
    min_latency_ms: float = Field(default=0.0, ge=0.0, description="Minimum request latency in ms")
    max_latency_ms: float = Field(default=0.0, ge=0.0, description="Maximum request latency in ms")
    std_dev_latency_ms: float = Field(
        default=0.0, ge=0.0, description="Standard deviation of request latencies in ms"
    )
    request_results: tuple[DirectVLLMRequestResult, ...] = Field(
        default_factory=tuple, description="Ordered per-request results"
    )
    warmup_count: int = Field(default=0, ge=0, description="Number of warmup requests executed")
    model_load_time_ms: float = Field(
        default=0.0, ge=0.0, description="Cold start model load time in ms"
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict, description="Execution environment and runtime metadata"
    )


class DirectVLLMRunner:
    """Direct vLLM execution engine bypassing InferOpt control plane."""

    def __init__(
        self,
        config: VLLMConfig | None = None,
        model_id: str = DEFAULT_VLLM_MODEL_ID,
        default_temperature: float = 0.0,
        default_max_tokens: int = 128,
        enforce_eager: bool = False,
        **kwargs: Any,
    ) -> None:
        """Initialize Direct vLLM runner.

        Args:
            config: Optional pre-constructed VLLMConfig model.
            model_id: Hugging Face model identifier (used if config is None).
            default_temperature: Sampling temperature (0.0 for greedy argmax).
            default_max_tokens: Default maximum tokens per request.
            enforce_eager: Disable CUDA graphs and force eager execution (diagnostic mode).
            **kwargs: Extra parameters passed to VLLMConfig constructor.
        """
        if config is not None:
            self._config = config
        elif kwargs or model_id != DEFAULT_VLLM_MODEL_ID or enforce_eager:
            cfg_kwargs: dict[str, Any] = {
                "model": model_id,
                "default_temperature": default_temperature,
                "default_max_tokens": default_max_tokens,
                "enforce_eager": enforce_eager,
            }
            cfg_kwargs.update(kwargs)
            self._config = VLLMConfig(**cfg_kwargs)
        else:
            self._config = VLLMConfig(
                model=model_id,
                default_temperature=default_temperature,
                default_max_tokens=default_max_tokens,
                enforce_eager=enforce_eager,
            )

        self._llm: Any = None
        self._model_load_time_ms: float = 0.0
        self._lock = asyncio.Lock()

    @property
    def model_id(self) -> str:
        """Target model identifier."""
        return self._config.model

    @property
    def config(self) -> VLLMConfig:
        """Active configuration model."""
        return self._config

    @property
    def is_loaded(self) -> bool:
        """True if model is loaded in memory."""
        return self._llm is not None

    @property
    def model_load_time_ms(self) -> float:
        """Measured cold start model load time in milliseconds."""
        return self._model_load_time_ms

    async def load_model(self) -> None:
        """Load vLLM engine into memory if not already loaded."""
        if self.is_loaded:
            return

        async with self._lock:
            if self.is_loaded:
                return

            def _load_sync() -> tuple[Any, float]:
                try:
                    import vllm  # type: ignore[import-not-found]
                except ImportError as err:
                    raise BackendError(
                        "vLLM dependencies not installed. "
                        "Install with: pip install 'inferopt[vllm]'"
                    ) from err

                t0 = time.perf_counter()
                engine_kwargs: dict[str, Any] = {
                    "model": self._config.model,
                    "gpu_memory_utilization": self._config.gpu_memory_utilization,
                    "tensor_parallel_size": self._config.tensor_parallel_size,
                    "dtype": self._config.dtype,
                    "trust_remote_code": self._config.trust_remote_code,
                }
                if self._config.max_model_len is not None:
                    engine_kwargs["max_model_len"] = self._config.max_model_len
                if self._config.seed is not None:
                    engine_kwargs["seed"] = self._config.seed
                if self._config.enforce_eager:
                    engine_kwargs["enforce_eager"] = True
                engine_kwargs.update(self._config.extra_engine_args)

                try:
                    llm_instance = vllm.LLM(**engine_kwargs)
                    load_ms = max(0.0, (time.perf_counter() - t0) * 1000.0)
                    return llm_instance, load_ms
                except Exception as exc:
                    raise BackendError(
                        f"Failed to initialize vLLM engine for '{self._config.model}': {exc}"
                    ) from exc

            self._llm, self._model_load_time_ms = await asyncio.to_thread(_load_sync)

    async def unload_model(self) -> None:
        """Safely release the initialized vLLM engine."""
        async with self._lock:
            self._llm = None
            self._model_load_time_ms = 0.0

            def _cleanup_sync() -> None:
                try:
                    import torch  # type: ignore[import-not-found]

                    if hasattr(torch, "cuda") and torch.cuda.is_available():
                        torch.cuda.empty_cache()
                except ImportError:
                    pass

            await asyncio.to_thread(_cleanup_sync)

    def _build_sampling_params(self, temperature: float, max_tokens: int) -> Any:
        """Construct a vLLM SamplingParams object."""
        try:
            import vllm
        except ImportError as err:
            raise BackendError(
                "vLLM dependencies not installed. Install with: pip install 'inferopt[vllm]'"
            ) from err

        sampling_kwargs: dict[str, Any] = {
            "temperature": max(0.0, temperature),
            "max_tokens": max(1, max_tokens),
        }
        sampling_kwargs.update(self._config.extra_sampling_args)
        return vllm.SamplingParams(**sampling_kwargs)

    async def warmup(self, count: int = 1) -> None:
        """Execute warmup requests to initialize CUDA graphs and memory pools.

        Args:
            count: Number of warmup iterations to execute.
        """
        if count <= 0:
            return

        await self.load_model()

        def _warmup_sync() -> None:
            import contextlib

            sampling_params = self._build_sampling_params(temperature=0.0, max_tokens=16)
            for _ in range(count):
                with contextlib.suppress(Exception):
                    self._llm.generate(
                        prompts=["Warmup probe query."],
                        sampling_params=sampling_params,
                        use_tqdm=False,
                    )

        await asyncio.to_thread(_warmup_sync)

    async def execute_request(self, spec: WorkloadRequestSpec) -> DirectVLLMRequestResult:
        """Execute a single request directly against vLLM.

        Args:
            spec: Workload request specification.

        Returns:
            DirectVLLMRequestResult with exact token counts, output hashes, and latency.
        """
        prompt_hash = compute_sha256(spec.prompt)
        temp = spec.temperature if spec.temperature >= 0.0 else self._config.default_temperature
        max_tok = spec.max_tokens if spec.max_tokens > 0 else self._config.default_max_tokens

        def _sync_gen() -> tuple[str, int, int, float]:
            t0 = time.perf_counter()
            sampling_params = self._build_sampling_params(temperature=temp, max_tokens=max_tok)
            outputs = self._llm.generate(
                prompts=[spec.prompt],
                sampling_params=sampling_params,
                use_tqdm=False,
            )
            lat_ms = max(0.0, (time.perf_counter() - t0) * 1000.0)

            if not outputs:
                raise RuntimeError(f"vLLM returned empty outputs for request {spec.request_id}")

            req_out = outputs[0]
            in_tokens = len(req_out.prompt_token_ids) if req_out.prompt_token_ids is not None else 0
            first_comp = req_out.outputs[0] if req_out.outputs else None
            gen_text = first_comp.text if first_comp is not None else ""
            out_tokens = (
                len(first_comp.token_ids) if first_comp and first_comp.token_ids is not None else 0
            )
            return gen_text, in_tokens, out_tokens, lat_ms

        try:
            gen_text, in_tokens, out_tokens, lat_ms = await asyncio.to_thread(_sync_gen)
            out_hash = compute_sha256(gen_text)
            return DirectVLLMRequestResult(
                request_id=spec.request_id,
                prompt=spec.prompt,
                prompt_hash=prompt_hash,
                generated_text=gen_text,
                output_hash=out_hash,
                input_tokens=in_tokens,
                output_tokens=out_tokens,
                latency_ms=lat_ms,
                success=True,
                error_message=None,
            )
        except Exception as exc:
            return DirectVLLMRequestResult(
                request_id=spec.request_id,
                prompt=spec.prompt,
                prompt_hash=prompt_hash,
                generated_text="",
                output_hash="",
                input_tokens=0,
                output_tokens=0,
                latency_ms=0.0,
                success=False,
                error_message=str(exc),
            )

    async def run(
        self,
        scenario: WorkloadScenario,
        warmup_count: int = 0,
        concurrency: int = 1,
        metadata: dict[str, Any] | None = None,
    ) -> DirectVLLMResult:
        """Execute a full workload scenario directly against vLLM with controlled concurrency.

        Args:
            scenario: Workload scenario containing ordered request specifications.
            warmup_count: Number of warmup requests to execute prior to timing.
            concurrency: Number of concurrent requests executed against the engine.
            metadata: Optional execution metadata.

        Returns:
            Aggregated DirectVLLMResult containing statistical summaries and request results.
        """
        await self.load_model()

        if warmup_count > 0:
            await self.warmup(count=warmup_count)

        sem = asyncio.Semaphore(max(1, concurrency))

        async def _bounded_submit(spec: WorkloadRequestSpec) -> DirectVLLMRequestResult:
            async with sem:
                return await self.execute_request(spec)

        t_start = time.perf_counter()
        tasks = [_bounded_submit(spec) for spec in scenario.requests]
        results_list = await asyncio.gather(*tasks)
        duration_sec = max(0.0001, time.perf_counter() - t_start)

        completed_results = [r for r in results_list if r.success]
        failed_count = len(results_list) - len(completed_results)
        completed_count = len(completed_results)

        latencies = [r.latency_ms for r in completed_results]
        in_tokens = [r.input_tokens for r in completed_results]
        out_tokens = [r.output_tokens for r in completed_results]

        total_in_tokens = sum(in_tokens)
        total_out_tokens = sum(out_tokens)
        avg_in_tokens = (total_in_tokens / completed_count) if completed_count > 0 else 0.0
        avg_out_tokens = (total_out_tokens / completed_count) if completed_count > 0 else 0.0
        min_out_tokens = min(out_tokens, default=0)
        max_out_tokens = max(out_tokens, default=0)

        rps = completed_count / duration_sec
        tok_ps = total_out_tokens / duration_sec

        avg_lat = (sum(latencies) / completed_count) if completed_count > 0 else 0.0
        p50_lat = calculate_percentile(latencies, 50.0) if latencies else 0.0
        p95_lat = calculate_percentile(latencies, 95.0) if latencies else 0.0
        p99_lat = calculate_percentile(latencies, 99.0) if latencies else 0.0
        min_lat = min(latencies, default=0.0)
        max_lat = max(latencies, default=0.0)
        std_dev_lat = compute_std_dev(latencies, avg_lat) if len(latencies) > 1 else 0.0

        return DirectVLLMResult(
            baseline_id=f"direct-vllm-{uuid.uuid4().hex[:8]}",
            timestamp=time.time(),
            scenario_name=scenario.scenario_name,
            model_id=self.model_id,
            duration_sec=duration_sec,
            total_requests=len(scenario.requests),
            completed_requests=completed_count,
            failed_requests=failed_count,
            requests_per_sec=rps,
            output_tokens_per_sec=tok_ps,
            total_input_tokens=total_in_tokens,
            total_output_tokens=total_out_tokens,
            avg_input_tokens_per_req=avg_in_tokens,
            avg_output_tokens_per_req=avg_out_tokens,
            min_output_tokens=min_out_tokens,
            max_output_tokens=max_out_tokens,
            avg_latency_ms=avg_lat,
            p50_latency_ms=p50_lat,
            p95_latency_ms=p95_lat,
            p99_latency_ms=p99_lat,
            min_latency_ms=min_lat,
            max_latency_ms=max_lat,
            std_dev_latency_ms=std_dev_lat,
            request_results=tuple(results_list),
            warmup_count=warmup_count,
            model_load_time_ms=self.model_load_time_ms,
            metadata=dict(metadata or {}),
        )
